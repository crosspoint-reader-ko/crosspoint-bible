"""Draw the CrossPoint Bible cover and write it as a C header for the boot and sleep screens.

Black, a triple-line cross with a sunburst where the bars cross, and a thin border
rule: the tooling of an old leather Bible, redrawn as clean lines (no photo pixels).
Geometry was measured from a reference photo: cross 154..464 px tall, bar 187..323,
lines about 4.5 px apart, scaled 1.5x here.

usage: python3 tools/bible/make_cover.py [src/images/BibleCover.h] [--png preview.png]
Needs Pillow (lib/EpdFont/scripts/venv has it).
"""
import math, sys
from PIL import Image, ImageDraw

W, H, SS = 480, 792, 4          # output size, supersampling
S = 1.5 * SS                    # reference px -> supersampled px
cx, cy = 240 * SS, 196 * SS     # crossing point
up, down, half = 71 * S, 239 * S, 68 * S
gap, lw = 4.6 * S, 2.0 * S      # line spacing, line width

img = Image.new("L", (W * SS, H * SS), 0)
d = ImageDraw.Draw(img)
for k in (-1, 0, 1):
    x = cx + k * gap
    d.rectangle((x - lw / 2, cy - up, x + lw / 2, cy + down), fill=255)
    y = cy + k * gap
    d.rectangle((cx - half, y - lw / 2, cx + half, y + lw / 2), fill=255)
# Sunburst around the crossing, between the bars.
rays = 24
for i in range(rays):
    a = (i + 0.5) * 2 * math.pi / rays
    r0 = 9 * S
    r1 = (19 if i % 2 == 0 else 14) * S
    d.line((cx + r0 * math.cos(a), cy + r0 * math.sin(a), cx + r1 * math.cos(a), cy + r1 * math.sin(a)),
           fill=255, width=int(1.4 * SS))
# Thin border rule, as on the book.
m = 16 * SS
d.rectangle((m, m, W * SS - m, H * SS - m), outline=255, width=int(2 * SS))

out = img.resize((W, H), Image.LANCZOS).point(lambda v: 255 if v > 110 else 0).convert("1")

args = sys.argv[1:]
png = None
if "--png" in args:
    png = args[args.index("--png") + 1]
    del args[args.index("--png") : args.index("--png") + 2]
    out.save(png)
header = args[0] if args else "src/images/BibleCover.h"

# 1 bit per pixel, rows top to bottom, MSB first; 1 = white (the cross), 0 = black.
data = bytearray()
px = out.load()
for y in range(H):
    for x0 in range(0, W, 8):
        b = 0
        for k in range(8):
            if x0 + k < W and px[x0 + k, y]:
                b |= 0x80 >> k
        data.append(b)
lines = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
with open(header, "w") as f:
    f.write("#pragma once\n// Generated by tools/bible/make_cover.py. Do not edit.\n#include <cstdint>\n\n")
    f.write(f"constexpr int BIBLE_COVER_WIDTH = {W};\nconstexpr int BIBLE_COVER_HEIGHT = {H};\n")
    f.write("// 1 bit per pixel, MSB first, 1 = white.\n")
    f.write(f"static const uint8_t BibleCover[{len(data)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n")
print(f"{header}: {W}x{H}, {len(data)} bytes")
